-- Статические страницы сайта, которые становятся редактируемыми через админку.
-- content пустой: структура и тексты страницы собираются в редакторе админки.
-- Публичный адрес определяется слагом (home -> /, остальные -> /<slug>).

SET NAMES utf8mb4;
SET CHARACTER SET utf8mb4;

USE it_services;

INSERT INTO pages (slug, title, meta_title, meta_description, status)
SELECT * FROM (
  SELECT 'home' AS slug, 'Главная' AS title, 'Разработка сайтов, CRM, базы данных, интеграции и AI — Литвинов Антон' AS meta_title,
          'Разработка сайтов, CRM-систем, баз данных, интеграций и AI-решений. Индивидуальный подход, удалённая работа по РФ. Краснодар.' AS meta_description, 'published' AS status
  UNION ALL SELECT 'portfolio', 'Портфолио', 'Портфолио — реализованные проекты',
          'Примеры выполненных проектов: сайты, CRM, интеграции, автоматизация. Кейсы с описанием задач и решений.', 'published'
  UNION ALL SELECT 'about', 'Обо мне', 'Обо мне — Литвинов Антон, разработчик',
          'Обо мне: опыт, стек, подход к работе. Разработка сайтов, CRM, баз данных, интеграции.', 'published'
  UNION ALL SELECT 'partners', 'Сотрудничество', 'Сотрудничество — для дизайнеров, маркетологов, студий',
          'Сотрудничество: партнёрская программа для дизайнеров, маркетологов, копирайтеров, студий и разработчиков.', 'published'
  UNION ALL SELECT 'contacts', 'Контакты', 'Контакты — Литвинов Антон',
          'Контакты: телефон, почта, форма заявки. Краснодар, удалённая работа по РФ.', 'published'
  UNION ALL SELECT 'policy', 'Политика конфиденциальности', 'Политика конфиденциальности',
          'Политика конфиденциальности в соответствии с 152-ФЗ: обработка персональных данных, цели, права пользователя.', 'published'
  UNION ALL SELECT 'terms', 'Пользовательское соглашение', 'Пользовательское соглашение',
          'Пользовательское соглашение — правила использования сайта, условия оказания услуг, ответственность сторон.', 'published'
) AS seed
WHERE NOT EXISTS (SELECT 1 FROM pages WHERE pages.slug = seed.slug);
